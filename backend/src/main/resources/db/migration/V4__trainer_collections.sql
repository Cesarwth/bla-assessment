-- Per-trainer collections: `pokemon` becomes the shared catalog (PokeAPI data only) and what a trainer chose to keep,
-- with their own notes, moves to `trainer_pokemon`. Portable SQL (the same script runs on H2 and PostgreSQL).
CREATE TABLE trainer_pokemon (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version    BIGINT       NOT NULL DEFAULT 0,
    user_id    BIGINT       NOT NULL,
    pokemon_id BIGINT       NOT NULL,
    nickname   VARCHAR(50),
    region     VARCHAR(50),
    added_at   TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_trainer_pokemon UNIQUE (user_id, pokemon_id),
    CONSTRAINT fk_trainer_pokemon_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT fk_trainer_pokemon_pokemon FOREIGN KEY (pokemon_id) REFERENCES pokemon (id) ON DELETE CASCADE
);

CREATE INDEX idx_trainer_pokemon_user ON trainer_pokemon (user_id);

CREATE TABLE trainer_pokemon_tags (
    trainer_pokemon_id BIGINT      NOT NULL,
    sort_order         INTEGER     NOT NULL,
    tag                VARCHAR(30) NOT NULL,
    PRIMARY KEY (trainer_pokemon_id, sort_order),
    CONSTRAINT fk_trainer_pokemon_tags_entry FOREIGN KEY (trainer_pokemon_id) REFERENCES trainer_pokemon (id) ON DELETE CASCADE
);

-- Existing owned rows become entries of their owner's collection; ownerless rows stay as catalog only.
INSERT INTO trainer_pokemon (user_id, pokemon_id, nickname, region, added_at)
SELECT owner_id, id, nickname, region, synced_at FROM pokemon WHERE owner_id IS NOT NULL;

INSERT INTO trainer_pokemon_tags (trainer_pokemon_id, sort_order, tag)
SELECT tp.id, t.sort_order, t.tag
FROM pokemon_tags t
JOIN trainer_pokemon tp ON tp.pokemon_id = t.pokemon_id;

DROP TABLE pokemon_tags;

-- Index and FK are dropped explicitly: H2 refuses to drop a column that a constraint or index still references.
DROP INDEX idx_pokemon_owner;
ALTER TABLE pokemon DROP CONSTRAINT fk_pokemon_owner;
ALTER TABLE pokemon DROP COLUMN owner_id;
ALTER TABLE pokemon DROP COLUMN nickname;
ALTER TABLE pokemon DROP COLUMN region;
