-- Local replica of PokeAPI data plus our own fields (nickname, region, tags).
-- Portable types only (the same script runs on H2 in tests and PostgreSQL in Docker).
CREATE TABLE pokemon (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version              BIGINT           NOT NULL DEFAULT 0,
    pokeapi_id           INTEGER          NOT NULL,
    name                 VARCHAR(100)     NOT NULL,
    sprite_url           VARCHAR(500),
    image_url            VARCHAR(500),
    weight_kg            DOUBLE PRECISION NOT NULL,
    height_m             DOUBLE PRECISION NOT NULL,
    genus                VARCHAR(100),
    description          VARCHAR(2000),
    evolution_chain_json VARCHAR(20000),
    nickname             VARCHAR(50),
    region               VARCHAR(50),
    synced_at            TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_pokemon_pokeapi_id UNIQUE (pokeapi_id)
);

CREATE TABLE pokemon_types (
    pokemon_id BIGINT      NOT NULL,
    sort_order INTEGER     NOT NULL,
    type_name  VARCHAR(50) NOT NULL,
    PRIMARY KEY (pokemon_id, sort_order),
    CONSTRAINT fk_pokemon_types_pokemon FOREIGN KEY (pokemon_id) REFERENCES pokemon (id) ON DELETE CASCADE
);

CREATE TABLE pokemon_abilities (
    pokemon_id   BIGINT       NOT NULL,
    sort_order   INTEGER      NOT NULL,
    ability_name VARCHAR(100) NOT NULL,
    PRIMARY KEY (pokemon_id, sort_order),
    CONSTRAINT fk_pokemon_abilities_pokemon FOREIGN KEY (pokemon_id) REFERENCES pokemon (id) ON DELETE CASCADE
);

CREATE TABLE pokemon_stats (
    pokemon_id BIGINT      NOT NULL,
    sort_order INTEGER     NOT NULL,
    stat_name  VARCHAR(50) NOT NULL,
    base_value INTEGER     NOT NULL,
    PRIMARY KEY (pokemon_id, sort_order),
    CONSTRAINT fk_pokemon_stats_pokemon FOREIGN KEY (pokemon_id) REFERENCES pokemon (id) ON DELETE CASCADE
);

CREATE TABLE pokemon_tags (
    pokemon_id BIGINT      NOT NULL,
    sort_order INTEGER     NOT NULL,
    tag        VARCHAR(30) NOT NULL,
    PRIMARY KEY (pokemon_id, sort_order),
    CONSTRAINT fk_pokemon_tags_pokemon FOREIGN KEY (pokemon_id) REFERENCES pokemon (id) ON DELETE CASCADE
);
